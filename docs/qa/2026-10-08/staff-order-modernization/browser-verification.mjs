async function screenshot(name,width) {
  await page.setViewportSize({width,height:1000});
  await page.evaluate(() => document.fonts.ready);
  await page.evaluate(() => {document.activeElement?.blur(); window.scrollTo({top:0,behavior:'instant'});});
  await page.waitForTimeout(300); // Settle the admin sidebar's 200 ms breakpoint transition before capturing it.
  await page.screenshot({path:path.join(evidence,`${name}-${width}.png`),fullPage:true});
  result.screenshots.push(`${name}-${width}.png`);
  const layout=await page.evaluate(() => ({width:innerWidth,contentWidth:document.querySelector('main')?.clientWidth,overflow:document.documentElement.scrollWidth-innerWidth,sidebarLeft:document.querySelector('[data-sidebar]')?.getBoundingClientRect().left,brokenImages:[...document.images].filter(img => !img.complete || img.naturalWidth === 0).map(img => img.src),actions:[...document.querySelectorAll('.staff-ordering a.ui-button,.staff-ordering button[type=submit]')].filter(el => el.getClientRects().length).map(el => ({text:el.textContent.trim(),height:el.getBoundingClientRect().height,left:el.getBoundingClientRect().left,right:el.getBoundingClientRect().right,position:getComputedStyle(el).position}))}));
  result.layouts.push({name,...layout});
  check(layout.overflow <= 1,`${name} has no horizontal overflow at ${width}`);
  check(layout.brokenImages.length === 0,`${name} photos load at ${width}`);
  check(layout.actions.every(item => item.left >= 0 && item.right <= width+1),`${name} actions stay within ${width}`);
  check(layout.actions.every(item => item.height >= 44),`${name} actions have 44px targets at ${width}`);
  if (width >= 1024) check(layout.sidebarLeft >= 0,`${name} keeps the desktop admin sidebar`);
}
